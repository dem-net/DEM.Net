using System;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Numerics;
using System.Text;
using System.Threading;
using System.Threading.Tasks;
using DEM.Net.Core;
using DEM.Net.glTF.Export;
using DEM.Net.glTF.SharpglTF;
using Microsoft.Extensions.DependencyInjection;
using SharpGLTF.Schema2;
using Xunit;

namespace DEM.Net.Test;

/// <summary>STL and OBJ exports of a small terrain mesh (offline)</summary>
public class ExportTests : IClassFixture<DemNetFixture>
{
    private const int Width = 20, Height = 10;
    private readonly ISTLExportService _stl;
    private readonly OBJExportService _obj;
    private readonly ModelRoot _model;

    public ExportTests(DemNetFixture fixture)
    {
        _stl = fixture.ServiceProvider.GetRequiredService<ISTLExportService>();
        _obj = fixture.ServiceProvider.GetRequiredService<OBJExportService>();
        var heightMap = new HeightMap(Width, Height)
        {
            Coordinates = [.. Enumerable.Range(0, Width * Height).Select(i => new GeoPoint(45.1 - (i / Width) * 0.001, 6 + (i % Width) * 0.001, 1000 + (i % 7) * 3))],
            Minimum = 1000,
            Maximum = 1018,
        };
        _model = fixture.ServiceProvider.GetRequiredService<SharpGltfService>()
            .CreateTerrainMesh(heightMap.ReprojectGeodeticToCartesian().CenterOnOrigin());
    }

    private MeshPrimitive Mesh => _model.LogicalMeshes[0].Primitives[0];
    // the terrain mesh is simplified: fewer triangles than the grid
    private int TriangleCount => Mesh.GetTriangleIndices().Count();
    private int VertexCount => Mesh.GetVertexAccessor("POSITION").Count;

    private (Vector3 A, Vector3 B, Vector3 C) FirstTriangle()
    {
        var positions = Mesh.GetVertexAccessor("POSITION").AsVector3Array();
        var (a, b, c) = Mesh.GetTriangleIndices().First();
        return (positions[a], positions[b], positions[c]);
    }

    private static string TempDirectory() => Path.Combine(Path.GetTempPath(), "DEM.Net.Tests", Guid.NewGuid().ToString("N"));

    [Fact]
    public async Task BinaryStlHasOneRecordPerTriangle()
    {
        using var stream = new MemoryStream();
        await _stl.WriteSTLAsync(Mesh, stream, ascii: false);
        var bytes = stream.ToArray();

        Assert.InRange(TriangleCount, 1, (Width - 1) * (Height - 1) * 2);
        Assert.Equal(TriangleCount, (int)BitConverter.ToUInt32(bytes, 80));
        Assert.Equal(84 + 50 * TriangleCount, bytes.Length);

        var (a, b, c) = FirstTriangle();
        float F(int i) => BitConverter.ToSingle(bytes, 84 + 4 * i);
        Assert.Equal(Vector3.Normalize(Vector3.Cross(b - a, c - a)), new Vector3(F(0), F(1), F(2)));
        Assert.Equal([a, b, c], [new Vector3(F(3), F(4), F(5)), new Vector3(F(6), F(7), F(8)), new Vector3(F(9), F(10), F(11))]);
    }

    [Fact]
    public async Task BinaryStlHeaderHasTheAttributions()
    {
        using var stream = new MemoryStream();
        await _stl.WriteSTLAsync(Mesh, stream, ascii: false,
            [new Attribution("Generator", "DEM Net Elevation API"),
             new Attribution("Mesh reduction", "Délatin (Mapbox), ISC License, and a long text past the 80 bytes of the header"),
             new Attribution("Digital Elevation Model", "SRTM_GL3 OpenTopography")]);
        var header = Encoding.ASCII.GetString(stream.ToArray(), 0, 80);

        // Generator skipped (elevationapi.com instead), data before mesh reduction, non ASCII replaced, truncated to the 80 bytes
        Assert.StartsWith("elevationapi.com; SRTM_GL3 OpenTopography; D?latin (Mapbox), ISC License, and a", header);
        Assert.DoesNotContain('\0', header);
        Assert.False(header.StartsWith("solid", StringComparison.Ordinal));
        Assert.Equal(TriangleCount, (int)BitConverter.ToUInt32(stream.ToArray(), 80));
    }

    [Fact]
    public async Task AsciiStlListsTheTriangles()
    {
        using var stream = new MemoryStream();
        await _stl.WriteSTLAsync(Mesh, stream, ascii: true, [new Attribution("Dataset", "Test")]);
        var lines = Encoding.UTF8.GetString(stream.ToArray()).Split(Environment.NewLine);

        Assert.Equal("solid Generated by elevationapi.com, Dataset: Test", lines[0]);
        Assert.Equal("endsolid Generated by elevationapi.com, Dataset: Test", lines[^2]);
        Assert.Equal("", lines[^1]);
        Assert.Equal(TriangleCount, lines.Count(l => l.StartsWith("  facet normal ")));
        Assert.Equal(2 + 7 * TriangleCount, lines.Length - 1);

        var (a, _, _) = FirstTriangle();
        Assert.Equal("    outer loop", lines[2]);
        Assert.Equal(string.Create(CultureInfo.InvariantCulture, $"      vertex {a.X:e6} {a.Y:e6} {a.Z:e6}"), lines[3]);
    }

    [Fact]
    public async Task StlFilesAreComplete()
    {
        var dir = TempDirectory();
        var file = Path.Combine(dir, "model.stl");
        try
        {
            await _stl.STLExportAsync(Mesh, file, ascii: false);
            Assert.Equal(84 + 50 * TriangleCount, new FileInfo(file).Length);

            // cancelled: the former file stays, no temporary file is left
            await Assert.ThrowsAnyAsync<OperationCanceledException>(() => _stl.STLExportAsync(Mesh, file, ascii: true, cancellationToken: new CancellationToken(true)));
            Assert.Equal(new[] { file }, Directory.GetFiles(dir));
            Assert.Equal(84 + 50 * TriangleCount, new FileInfo(file).Length);
        }
        finally
        {
            Directory.Delete(dir, recursive: true);
        }
    }

    [Fact]
    public async Task ObjExportWritesVerticesAndFaces()
    {
        var dir = TempDirectory();
        try
        {
            var file = await _obj.ExportGlTFModelToWaveFrontObjAsync(_model, Path.Combine(dir, "obj"), "terrain");
            var lines = await File.ReadAllLinesAsync(file);

            Assert.Equal(Path.Combine(dir, "obj", "terrain.obj"), file);
            Assert.Equal("mtllib terrain.mtl", lines[3]);
            Assert.Equal(VertexCount, lines.Count(l => l.StartsWith("v ")));
            Assert.Equal(TriangleCount, lines.Count(l => l.StartsWith("f ")));

            var first = Mesh.GetVertexAccessor("POSITION").AsVector3Array()[0];
            Assert.Equal(string.Create(CultureInfo.InvariantCulture, $"v {first.X} {first.Y} {first.Z}"), lines.First(l => l.StartsWith("v ")));

            var zip = await _obj.ExportGlTFModelToWaveFrontObjAsync(_model, Path.Combine(dir, "obj"), "terrain", overwrite: true, zip: true);
            Assert.Equal(Path.Combine(dir, "terrain.zip"), zip);
            Assert.False(Directory.Exists(Path.Combine(dir, "obj")));
            using var archive = System.IO.Compression.ZipFile.OpenRead(zip);
            Assert.Equal(["terrain.mtl", "terrain.obj"], archive.Entries.Select(e => e.FullName).Order());
        }
        finally
        {
            Directory.Delete(dir, recursive: true);
        }
    }
}
